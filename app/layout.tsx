import type { Metadata, Viewport } from "next";
import { Space_Grotesk, Space_Mono } from "next/font/google";
import Nav from "@/components/Nav";
import Footer from "@/components/Footer";
import { AuthProvider } from "@/lib/auth-context";
import "./globals.css";

const spaceGrotesk = Space_Grotesk({
  subsets: ["latin"],
  weight: ["300", "400", "500", "600", "700"],
  variable: "--font-space-grotesk",
});

const spaceMono = Space_Mono({
  subsets: ["latin"],
  weight: ["400", "700"],
  variable: "--font-space-mono",
});

// Installable as a home screen app (see public/manifest.json). The icon is
// the black "q" tile from public/icons/icon.svg.
export const metadata: Metadata = {
  title: "Qoyl",
  description: "Personalized hair care for every texture.",
  manifest: "/manifest.json",
  icons: {
    icon: "/icons/icon-192.png",
    apple: "/icons/icon-192.png",
  },
  appleWebApp: {
    capable: true,
    statusBarStyle: "black-translucent",
    title: "Qoyl",
  },
};

// maximumScale/userScalable: false stops pinch-zoom from getting stuck
// mid-gesture on mobile (the reported symptom); viewportFit: "cover"
// extends the layout under the iPhone notch/home-indicator safe areas
// that env(safe-area-inset-*) below then insets content back out of.
// themeColor sets the browser chrome (Android) and status bar tint (iOS
// standalone). Black by default; pages that are white can override it via
// their own viewport export.
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
  viewportFit: "cover",
  themeColor: "#0a0a0a",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <head>
        {/* Next emits the apple-mobile-web-app-* tags from appleWebApp above;
            this one isn't generated by Next. */}
        <meta name="mobile-web-app-capable" content="yes" />
      </head>
      <body
        className={`${spaceGrotesk.variable} ${spaceMono.variable} antialiased`}
      >
        <AuthProvider>
          <Nav />
          {children}
          <Footer />
        </AuthProvider>
      </body>
    </html>
  );
}

import type { Metadata, Viewport } from "next";
import { Space_Grotesk, Space_Mono, Fredoka, Lora, DM_Sans } from "next/font/google";
import Nav from "@/components/Nav";
import Footer from "@/components/Footer";
import FeedbackSurveyTrigger from "@/components/FeedbackSurveyTrigger";
import HomeScreenPrompt from "@/components/HomeScreenPrompt";
import ServiceWorkerRegistrar from "@/components/ServiceWorkerRegistrar";
import { AuthProvider } from "@/lib/auth-context";
import "./globals.css";

const spaceGrotesk = Space_Grotesk({
  subsets: ["latin"],
  weight: ["300", "400", "500", "600", "700"],
  variable: "--font-space-grotesk",
  display: "swap",
  preload: false,
});

const spaceMono = Space_Mono({
  subsets: ["latin"],
  weight: ["400", "700"],
  variable: "--font-space-mono",
  display: "swap",
  preload: false,
});

// Display font for headings/hero text - hand-drawn, bouncy rounded feel
// closest to the "Sunday Dinner Club" reference logo. Self-hosted via
// next/font (this app has no <link> tags for fonts anywhere - Space
// Grotesk/Mono both load this way), not the literal CSS2 <link> the
// request specified. The requested family name "Fredoka One" isn't a
// real next/font/google export (confirmed via a scratch tsc check) -
// "Fredoka" is the current variable-weight family Google Fonts
// replaced it with, and is the actual hand-drawn-rounded face behind
// the old "Fredoka One" name.
const fredoka = Fredoka({
  subsets: ["latin"],
  weight: ["400", "500", "600", "700"],
  variable: "--font-fredoka",
  display: "swap",
  preload: false,
});

// Lora and DM Sans used by the ShowerShelfCart checkout page.
const lora = Lora({
  subsets: ["latin"],
  weight: ["400", "600"],
  variable: "--font-lora",
  display: "swap",
  preload: false,
});

const dmSans = DM_Sans({
  subsets: ["latin"],
  weight: ["400", "500", "600"],
  variable: "--font-dm-sans",
  display: "swap",
  preload: false,
});

// Installable as a home screen app (see public/manifest.json). The icon is
// the black "q" tile from public/icons/icon.svg.
export const metadata: Metadata = {
  title: "Qoyl",
  description: "Personalized hair care for every texture.",
  manifest: "/manifest.json",
  icons: {
    icon: "/icons/icon-192.png",
    apple: "/icons/icon-192.png",
  },
  appleWebApp: {
    capable: true,
    statusBarStyle: "black-translucent",
    title: "Qoyl",
  },
};

// maximumScale/userScalable: false stops pinch-zoom from getting stuck
// mid-gesture on mobile (the reported symptom); viewportFit: "cover"
// extends the layout under the iPhone notch/home-indicator safe areas
// that env(safe-area-inset-*) below then insets content back out of.
// themeColor sets the browser chrome (Android) and status bar tint (iOS
// standalone). Black by default; pages that are white can override it via
// their own viewport export.
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
  viewportFit: "cover",
  themeColor: "#0a0a0a",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <head>
        {/* Next emits the apple-mobile-web-app-* tags from appleWebApp above;
            this one isn't generated by Next. */}
        <meta name="mobile-web-app-capable" content="yes" />
      </head>
      <body
        className={`${spaceGrotesk.variable} ${spaceMono.variable} ${fredoka.variable} ${lora.variable} ${dmSans.variable} antialiased`}
      >
        <AuthProvider>
          <Nav />
          {children}
          <Footer />
          <FeedbackSurveyTrigger />
          <HomeScreenPrompt />
          <ServiceWorkerRegistrar />
        </AuthProvider>
      </body>
    </html>
  );
}
